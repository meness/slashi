/** Picks a fitting Phosphor icon for free text such as a command title. */
export function pickIcon(text: string, fallback = 'lightning'): string {
  for (const [pattern, icon] of RULES) if (pattern.test(text)) return icon;
  return fallback;
}

/** Every icon name Slashi can produce from rules — validated against the Phosphor catalog in tests. */
export function ruleIcons(): string[] {
  return RULES.map(([, icon]) => icon);
}

