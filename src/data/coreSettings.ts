// Popular core VS Code settings. VS Code doesn't expose core setting metadata to extensions,
// so these are curated; settings contributed by extensions (including built-ins like Git) are read at runtime.

export interface SettingMeta {
  key: string;
  type: 'boolean' | 'number' | 'string' | 'enum' | 'array' | 'object';
  description: string;
  enum?: string[];
  enumDescriptions?: string[];
}

const b = (key: string, description: string): SettingMeta => ({ key, type: 'boolean', description });
const n = (key: string, description: string): SettingMeta => ({ key, type: 'number', description });
const s = (key: string, description: string): SettingMeta => ({ key, type: 'string', description });
const e = (key: string, description: string, values: string[]): SettingMeta => ({ key, type: 'enum', description, enum: values });

